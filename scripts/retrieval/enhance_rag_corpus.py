def infer_issue_type(tags):
    for tag in tags:
        if tag in TAG_TO_ISSUE_TYPE:
            return TAG_TO_ISSUE_TYPE[tag]
    return ""


def main():
    docs = []
    with open(CORPUS_PATH, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                docs.append(json.loads(line))

    existing_ids = {d["id"] for d in docs}
    updated = 0
    for doc in docs:
        if not doc.get("issue_type"):
            it = infer_issue_type(doc.get("tags", []))
            if it:
                doc["issue_type"] = it
                updated += 1

    added = 0
    for case in NEW_CASES:
        if case["id"] not in existing_ids:
            docs.append(case)
            added += 1

    with open(CORPUS_PATH, "w", encoding="utf-8") as f:
        for doc in docs:
            f.write(json.dumps(doc, ensure_ascii=False) + "\n")

    print(f"现有语料补充 issue_type: {updated} 条")
    print(f"新增案例: {added} 条")
    print(f"语料总量: {len(docs)} 条")

    from collections import Counter
    dc = Counter(d.get("district", "") for d in docs)
    itc = Counter(d.get("issue_type", "") for d in docs)
    print(f"\n区分布: {dict(dc.most_common())}")
    print(f"事项类型分布: {dict(itc.most_common())}")


if __name__ == "__main__":
    main()
